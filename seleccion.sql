--  DDL for Procedure SP_CONTRATAR_MEJORES
--------------------------------------------------------
set define off;

  CREATE OR REPLACE NONEDITIONABLE PROCEDURE "SP_CONTRATAR_MEJORES" (
    p_cantidad IN NUMBER, 
    p_sueldo_base IN NUMBER
) AS
BEGIN
    INSERT INTO empleados (cedula, nombre, fecha_ingreso, sueldo)
    SELECT c.cedula, c.nombre, SYSDATE, p_sueldo_base
    FROM candidatos c
    JOIN cabeceras_evaluacion ce ON c.cedula = ce.cedula_candidato
    JOIN detalles_evaluacion de ON ce.numero_evaluacion = de.numero_evaluacion
    GROUP BY c.cedula, c.nombre
    ORDER BY SUM(de.calificacion) DESC
    FETCH FIRST p_cantidad ROWS ONLY;

    COMMIT;
END;
