--  DDL for Trigger TRG_VALIDAR_CALIFICACION
--------------------------------------------------------

  CREATE OR REPLACE NONEDITIONABLE TRIGGER "TRG_VALIDAR_CALIFICACION" 
BEFORE INSERT OR UPDATE ON detalles_evaluacion
FOR EACH ROW
DECLARE
    v_maximo NUMBER(5,2);
BEGIN
    SELECT puntaje_maximo INTO v_maximo
    FROM parametros_evaluacion
    WHERE codigo_parametro = :NEW.codigo_parametro;

    IF :NEW.calificacion > v_maximo THEN
        RAISE_APPLICATION_ERROR(-20001, 'Error: La calificación (' || :NEW.calificacion || 
                                ') supera el puntaje máximo permitido (' || v_maximo || ') para este parámetro.');
    END IF;
END;

